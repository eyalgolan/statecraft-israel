using System.Globalization;
using System.Text;
using Statecraft.Sim;

// R-EFX-001, R-EFX-002, #1718 (Done-when: "The PR attaches a complete inventory keyed by event + option + effect field:
// old target, new validated target or "legacy rulesets only", expected delta, and whether the card's review is reset.
// No row is unresolved."). docs/gdd03-event-inventory.md is checked against what the loader does with the real content,
// so the inventory cannot drift from the cards or from content/gdd03-events.yaml. STATECRAFT_UPDATE_GOLDEN=1 rewrites
// the generated block, as for the goldens; review the diff before committing it.
public class Gdd03EventInventoryTests
{
    const string Begin = "<!-- inventory:begin (generated by Gdd03EventInventoryTests; do not edit by hand) -->";
    const string End = "<!-- inventory:end -->";

    static string DocPath() =>
        Path.Combine(Directory.GetParent(RealContentTests.ContentRoot())!.FullName, "docs", "gdd03-event-inventory.md");

    static string Num(double v) => v.ToString("G", CultureInfo.InvariantCulture);

    /// <summary>Every effect field of every option, in the card's own order: set_policy (by key), set_rung, effects, then
    /// the structured grant_units, city_effects and unlock_projects. Same-target effects keep their list index.</summary>
    static IEnumerable<(string Field, string Change)> Fields(EventOption o)
    {
        foreach (var kv in o.SetPolicy.OrderBy(kv => kv.Key, StringComparer.Ordinal))
            yield return ($"set_policy.{kv.Key}", "set " + Num(kv.Value));
        if (o.SetRung.HasValue) yield return ("set_rung", "set " + o.SetRung.Value.ToString(CultureInfo.InvariantCulture));
        for (int i = 0; i < o.Effects.Count; i++)
            yield return ($"effects[{i}].{o.Effects[i].Target}", Num(o.Effects[i].Delta));
        for (int i = 0; i < o.GrantUnits.Count; i++)
            yield return ($"grant_units[{i}]", $"{o.GrantUnits[i].N} {o.GrantUnits[i].Type}");
        for (int i = 0; i < o.CityEffects.Count; i++)
            yield return ($"city_effects[{i}].{o.CityEffects[i].City}.{o.CityEffects[i].Field}", Num(o.CityEffects[i].Delta));
        for (int i = 0; i < o.UnlockProjects.Count; i++)
            yield return ($"unlock_projects[{i}]", o.UnlockProjects[i]);
    }

    static string Render()
    {
        var old = Gdd03EventRulesTests.Real(false);
        var modern = Gdd03EventRulesTests.Real(true);
        var kept = modern.Events.ToDictionary(e => e.Id);
        var excluded = old.Events.Where(e => !kept.ContainsKey(e.Id)).Select(e => e.Id).ToList();
        var sb = new StringBuilder();
        sb.Append(Begin).Append('\n').Append('\n');
        sb.Append("| Event | Option | Effect field (old target) | Old delta | gdd-0.3 target | gdd-0.3 delta | Review reset |\n");
        sb.Append("|---|---|---|---|---|---|---|\n");
        int rows = 0;
        foreach (var e in old.Events.OrderBy(e => e.Id, StringComparer.Ordinal))
        {
            kept.TryGetValue(e.Id, out var m);
            // "Review reset: no": a kept card keeps its status and human sign-off; an excluded card is not loaded at all.
            if (m != null) { Assert.Equal(e.Status, m.Status); Assert.Equal(e.ReviewedBy, m.ReviewedBy); Assert.Equal(e.ReviewedOn, m.ReviewedOn); }
            foreach (var o in e.Options)
            {
                // A kept card is the same record under gdd-0.3: its option and every field load unchanged.
                var mo = m?.Options.Single(x => x.Id == o.Id);
                var newFields = mo == null ? null : Fields(mo).ToList();
                var oldFields = Fields(o).ToList();
                if (newFields != null) Assert.Equal(oldFields, newFields);
                // No row is unresolved: the shipped cards carry no structured effect, which gdd-0.3 refuses outright.
                Assert.Empty(o.GrantUnits); Assert.Empty(o.CityEffects); Assert.Empty(o.UnlockProjects);
                foreach (var (field, change) in oldFields)
                {
                    rows++;
                    var (target, delta) = m == null
                        ? ("legacy rulesets only (card excluded)", "none (not in play)")
                        : ($"`{field}` (same)", change);
                    sb.Append($"| `{e.Id}` | `{o.Id}` | `{field}` | {change} | {target} | {delta} | no |\n");
                }
            }
        }
        sb.Append('\n').Append($"{rows} rows: {old.Events.Count} cards under gdd-0.1, {modern.Events.Count} under gdd-0.3.\n");

        // What the gdd-0.3 loader says about each excluded card if its exclusion alone were removed: the first field it
        // refuses, or that the whole card loads. This is a probe only; content/gdd03-events.yaml is unchanged.
        sb.Append('\n').Append("| Excluded card | gdd-0.3 loader with only this exclusion removed |\n|---|---|\n");
        foreach (var id in excluded.OrderBy(x => x, StringComparer.Ordinal))
        {
            var manifest = "ruleset: gdd-0.3\nexclusions:\n" + string.Concat(excluded.Where(x => x != id)
                .Select(x => $"  - {{ id: {x}, reason: inventory probe }}\n"));
            string verdict;
            try { Gdd03EventRulesTests.Real(true, manifest); verdict = "loads: every field passes the gdd-0.3 checks"; }
            catch (ContentException ex) { verdict = $"refused at `{ex.Field}`: {ex.Message.Substring(ex.Message.LastIndexOf(": ", StringComparison.Ordinal) + 2)}"; }
            sb.Append($"| `{id}` | {verdict} |\n");
        }
        sb.Append('\n').Append(End);
        return sb.ToString();
    }

    // R-EFX-001, R-EFX-002
    [Fact]
    public void R_EFX_001_TheInventoryListsEveryEffectFieldAsTheGdd03LoaderResolvesIt()
    {
        var expected = Render();
        var path = DocPath();
        var doc = File.ReadAllText(path).Replace("\r\n", "\n");
        int b = doc.IndexOf(Begin, StringComparison.Ordinal), e = doc.IndexOf(End, StringComparison.Ordinal);
        Assert.True(b >= 0 && e > b, $"{path} needs the {Begin} ... {End} block");
        var block = doc.Substring(b, e + End.Length - b);
        if (GoldenManifest.UpdateRequested && block != expected)
        {
            File.WriteAllText(path, doc.Substring(0, b) + expected + doc.Substring(e + End.Length));
            return;
        }
        Assert.Equal(expected, block);
    }
}
