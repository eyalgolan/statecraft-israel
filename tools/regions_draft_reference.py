"""Writes research_notes/gdd03-regions.approved-draft.yaml (#1691): the per-identity membership and opening-control
values of the owner-approved region draft, so a test can compare the imported evidence against the approved draft
without the 2.4 MB draft living in the repository.

  uv run tools/regions_draft_reference.py <path to regions-1691.draft.yaml> [output]

The header records the draft's own id, byte size and SHA-256, so anyone holding the approved file can rerun this and
get the same output. For each region, in the draft's order: id, capital_place_id, binding_status and opening_control
status and value; for each member, in the draft's order: id, region_id, binding_status and opening_control status,
value and date. Nothing else is copied (no sources, names or coordinates)."""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "research_notes" / "gdd03-regions.approved-draft.yaml"


def flow(row: dict) -> str:
    """One member as a YAML flow mapping on one line; JSON scalars are valid YAML and keep null distinct from text."""
    return "{ " + ", ".join(f"{k}: {json.dumps(v, ensure_ascii=False)}" for k, v in row.items()) + " }"


def reference(raw: bytes) -> str:
    draft = yaml.safe_load(raw)
    out = [
        "# Generated by tools/regions_draft_reference.py from the owner-approved #1691 region draft; do not edit by hand.",
        "# Per-identity membership and opening control only. Gdd03RegionAuthoringTests compares the imported evidence",
        "# (gdd03-regions-capitals-fields.yaml) with it, identity by identity.",
        "source:",
        f"  draft: {json.dumps(draft['draft'])}",
        f"  bytes: {len(raw)}",
        f"  sha256: {hashlib.sha256(raw).hexdigest()}",
        "regions:",
    ]
    for r in draft["regions"]:
        control = r["opening_control"]
        fields = {"id": r["id"], "capital_place_id": r["capital_place_id"], "binding_status": r["binding_status"],
                  "control_status": control.get("status"), "control_value": control.get("value")}
        out += [("  - " if i == 0 else "    ") + f"{k}: {json.dumps(v, ensure_ascii=False)}" for i, (k, v) in enumerate(fields.items())]
        out.append("    members:")
        for m in r["members"]:
            control = m["opening_control"]
            out.append("      - " + flow({"id": m["id"], "region_id": m["region_id"], "binding_status": m["binding_status"],
                                          "control_status": control.get("status"), "control_value": control.get("value"),
                                          "control_date": control.get("date")}))
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) not in (2, 3):
        print(__doc__, file=sys.stderr)
        return 2
    out = Path(argv[2]) if len(argv) == 3 else OUT
    out.write_text(reference(Path(argv[1]).read_bytes()), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
