"""Unit anchor -> hex for the simulation's starting forces (R-UNIT-006).

Usage: uv run tools/unit_anchor_hexes.py   (reads content/map/hexes.json and content/map/units_1948.yaml,
writes content/map/unit_anchor_hexes.yaml)
Each anchor's hex is the one holding its coordinates, by the map's projection and cube rounding (hexgrid.lonlat_to_km,
hexgrid.point_to_hex; Unity's HexPicker does the same). The sim reads the result instead of re-implementing the
projection, so it needs no trigonometry (docs/determinism.md: no libm calls in the sim), as for settlement_hexes.py."""
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import hexgrid as hg  # noqa: E402
import yaml12  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
MAP = ROOT / "content" / "map"
OUT = MAP / "unit_anchor_hexes.yaml"
HEADER = ("# Generated by tools/unit_anchor_hexes.py from units_1948.yaml and hexes.json (hexgrid.lonlat_to_km, point_to_hex).\n"
          "# Do not edit by hand: rerun the tool after changing either input. anchor is the index in the row's anchors list.\n")


def render(hexes: dict, units: list[dict]) -> str:
    """The file text: one flow mapping per anchor, in units_1948.yaml order."""
    lines = [HEADER, "anchors:\n"]
    for u in units:
        for k, a in enumerate(u.get("anchors") or []):
            x, y = hg.lonlat_to_km(a["lon"], a["lat"], hexes["bounds"])
            (q,), (r,) = hg.point_to_hex(np.array([x]), np.array([y]), hexes["hex_size_km"])
            lines.append(f"  - {{ id: {u['id']}, anchor: {k}, q: {q}, r: {r} }}\n")
    return "".join(lines)


def main() -> None:
    hexes = json.loads((MAP / "hexes.json").read_text())
    units = yaml12.load((MAP / "units_1948.yaml").read_text(encoding="utf-8"))["units"]
    OUT.write_text(render(hexes, units))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(units)} units)")


if __name__ == "__main__":
    main()
